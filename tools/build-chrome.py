#!/usr/bin/env python3
"""Build the Chrome (MV3) variant of the add-on into dist/chrome/ and dist/*-chrome.zip.

One source tree, two browsers. `extension/` stays exactly what it was (the Firefox build, and what
gets signed for AMO); this script copies it and rewrites the only two things Chrome refuses:

* ``background.scripts`` — a Firefox-only MV3 key — becomes ``background.service_worker``, pointing
  at a generated ``background.sw.js`` that ``importScripts()`` the same files in the same order;
* ``browser_specific_settings`` — a Gecko-only key — is dropped.

Everything else is passed through untouched, and the Chrome-side manifest limits are asserted here
so a Firefox-side edit Chrome would reject fails at build time instead of at load time.

Usage:  tools/build-chrome.py [--out DIR] [--print-manifest]
"""

from __future__ import annotations

import argparse
import json
import shutil
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "extension"

#: Chrome accepts at most these; a longer value makes the whole manifest invalid.
NAME_LIMIT = 75
DESCRIPTION_LIMIT = 132

#: The service worker entry point generated below, and the files it pulls in (the order matters:
#: background.js uses SecureVaultClient and SecureVaultTotp at load time).
SW_ENTRY = "background.sw.js"
SW_FILES = ["lib/browser-compat.js", "lib/vault-client.js", "lib/totp.js", "background.js"]

#: Minimum Chrome this build is meant for: MV3 service workers, the scripting API, and the
#: promise-returning flavour of chrome.* that background.js relies on.
MINIMUM_CHROME_VERSION = "110"

SW_BODY = """/*
 * Chrome's service worker entry point.
 *
 * Generated by tools/build-chrome.py — do not edit here; edit extension/ instead.
 *
 * Chrome MV3 has no background *page*: `background.scripts` is a Firefox-only key, so the same
 * files are pulled in here, in the same order, by importScripts().
 */
importScripts({files});
"""


def chrome_manifest(source: dict) -> dict:
    """Transform the Firefox manifest into the Chrome one, asserting the Chrome-only limits."""
    manifest = json.loads(json.dumps(source))  # deep copy; the caller's dict is left alone

    background = manifest.get("background") or {}
    scripts = background.get("scripts")
    if not scripts:
        raise SystemExit("extension/manifest.json has no background.scripts to convert")
    if [str(item) for item in scripts] != SW_FILES:
        raise SystemExit(
            "background.scripts changed; update SW_FILES in tools/build-chrome.py to match:\n"
            f"  manifest: {scripts}\n  expected: {SW_FILES}"
        )

    manifest["background"] = {"service_worker": SW_ENTRY}
    manifest.pop("browser_specific_settings", None)
    manifest["minimum_chrome_version"] = MINIMUM_CHROME_VERSION

    name = str(manifest.get("name") or "")
    description = str(manifest.get("description") or "")
    if len(name) > NAME_LIMIT:
        raise SystemExit(f"name is {len(name)} characters; Chrome allows {NAME_LIMIT}")
    if len(description) > DESCRIPTION_LIMIT:
        raise SystemExit(
            f"description is {len(description)} characters; Chrome allows {DESCRIPTION_LIMIT}"
        )
    parts = str(manifest.get("version") or "").split(".")
    if not 1 <= len(parts) <= 4 or not all(part.isdigit() and int(part) <= 65535 for part in parts):
        raise SystemExit(f"version {manifest.get('version')!r} is not a Chrome version")

    # The point of the transform: everything that is not one of the two Chrome-specific deltas is
    # carried over verbatim, so the two builds cannot drift apart silently.
    unchanged = {
        key: value
        for key, value in source.items()
        if key not in ("background", "browser_specific_settings")
    }
    for key, value in unchanged.items():
        if manifest.get(key) != value:
            raise SystemExit(f"key {key!r} did not survive the transform")
    return manifest


def build(out_dir: Path, print_manifest: bool) -> int:
    if not (SOURCE / "manifest.json").is_file():
        raise SystemExit(f"no extension tree at {SOURCE}")
    source_manifest = json.loads((SOURCE / "manifest.json").read_text(encoding="utf-8"))
    manifest = chrome_manifest(source_manifest)

    if print_manifest:
        print(json.dumps(manifest, indent=2, ensure_ascii=False))
        return 0

    if out_dir.exists():
        shutil.rmtree(out_dir)
    out_dir.parent.mkdir(parents=True, exist_ok=True)
    shutil.copytree(
        SOURCE,
        out_dir,
        ignore=shutil.ignore_patterns(".DS_Store", "__MACOSX", "*.pyc"),
    )
    (out_dir / SW_ENTRY).write_text(
        SW_BODY.format(files=", ".join(json.dumps(name) for name in SW_FILES)), encoding="utf-8"
    )
    (out_dir / "manifest.json").write_text(
        json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )

    archive = ROOT / "dist" / f"secure-vault-browser-{manifest['version']}-chrome.zip"
    archive.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(archive, "w", zipfile.ZIP_DEFLATED) as bundle:
        for path in sorted(out_dir.rglob("*")):
            if path.is_file():
                bundle.write(path, path.relative_to(out_dir).as_posix())

    print(f"built: {out_dir}")
    print(f"built: {archive}")
    print(f"  manifest: {json.dumps({k: manifest[k] for k in ('name', 'version', 'minimum_chrome_version')}, ensure_ascii=False)}")
    print(f"  background: {manifest['background']['service_worker']} -> {', '.join(SW_FILES)}")
    print(f"  service worker size: {(out_dir / SW_ENTRY).stat().st_size} bytes")
    print(f"  files: {sum(1 for p in out_dir.rglob('*') if p.is_file())}")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", default=str(ROOT / "dist" / "chrome"), help="output directory")
    parser.add_argument("--print-manifest", action="store_true", help="print the Chrome manifest and stop")
    args = parser.parse_args()
    return build(Path(args.out).expanduser().resolve(), args.print_manifest)


if __name__ == "__main__":
    sys.exit(main())
